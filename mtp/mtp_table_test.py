"""Test #3: does an n-gram table help a multi-token-prediction (draft) head?

Frozen base model (Qwen3-0.6B-Base by default). Medusa-style draft heads read the base's
final hidden state at position t plus the embedding of the base's own next token x[t+1]
(as EAGLE does) and propose tokens x[t+2..t+1+K]. Speculative decoding verifies drafts
against the base, so output never changes; what matters is how many drafted tokens the
base accepts per step.

Arms
  generic        head trained on general web text (FineWeb-Edu)
  domain         head trained on biomedical text (Biomed-Enriched)
  domain_big     domain head with a 4x wider MLP (roughly parameter-matched to the table arms)
  domain_table   domain head + learned hashed bigram/trigram table over (.., x[t], x[t+1])
  domain_rand    same, table rows frozen at their random init (control)
  lookup         training-free: most frequent next token after the last two tokens, chained
  domain+lookup  two draft branches verified together; accept the longer match

Metric: on greedy continuations generated by the base from held-out prompts, the mean
number of tokens produced per verification step = 1 + accepted draft tokens (chain
drafting, greedy verification), reported separately for biomedical and general text.
"""

import argparse
import json
import math
import os
import time

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F


# ----------------------------------------------------------------------------- data

def iter_parquet_texts(path, filt, max_docs, skip=0):
    import pyarrow.parquet as pq
    import pyarrow.compute as pc
    f = pq.ParquetFile(path)
    seen = 0
    for rb in f.iter_batches(batch_size=2048, columns=["text", "language", "domain", "educational_score"]):
        t = rb.to_pydict()
        for text, lang, dom, edu in zip(t["text"], t["language"], t["domain"], t["educational_score"]):
            if not filt(lang, dom, edu):
                continue
            seen += 1
            if seen <= skip:
                continue
            yield text
            if seen - skip >= max_docs:
                return


def iter_hf_texts(name, config, max_docs, skip=0):
    from datasets import load_dataset
    ds = load_dataset(name, config, split="train", streaming=True)
    for i, row in enumerate(ds):
        if i < skip:
            continue
        if i - skip >= max_docs:
            return
        yield row["text"]


def pack_tokens(texts, tok, n_tokens, seq_len):
    buf, out = [], []
    total = 0
    for text in texts:
        ids = tok(text, add_special_tokens=False)["input_ids"] + [tok.eos_token_id]
        buf.extend(ids)
        while len(buf) >= seq_len:
            out.append(buf[:seq_len])
            buf = buf[seq_len:]
            total += seq_len
            if total >= n_tokens:
                return torch.tensor(out, dtype=torch.long)
    return torch.tensor(out, dtype=torch.long)


def prompts_from(texts, tok, n, plen):
    out = []
    for text in texts:
        ids = tok(text, add_special_tokens=False)["input_ids"]
        if len(ids) >= plen:
            out.append(ids[:plen])
        if len(out) >= n:
            break
    return torch.tensor(out, dtype=torch.long)


# --------------------------------------------------------------------------- modules

def _primes_from(start, n):
    out, c = [], start
    while len(out) < n:
        c += 1
        if all(c % d for d in range(2, int(c ** 0.5) + 1)):
            out.append(c)
    return out


class NgramTable(nn.Module):
    """Hashed bigram + trigram table over token ids ending at each position."""

    def __init__(self, hidden, rows=20000, heads=8, dim=64, seed=1234, frozen=False):
        super().__init__()
        self.orders = (2, 3)
        self.heads = heads
        primes = _primes_from(rows, heads * len(self.orders))
        self.register_buffer("primes", torch.tensor(primes, dtype=torch.long), persistent=False)
        offs = np.cumsum([0] + primes[:-1])
        self.register_buffer("offsets", torch.tensor(offs, dtype=torch.long), persistent=False)
        g = np.random.default_rng(seed)
        mult = g.integers(1, 2**31, size=(len(self.orders), 3), dtype=np.int64) * 2 + 1
        self.register_buffer("mult", torch.tensor(mult, dtype=torch.long), persistent=False)
        self.emb = nn.Embedding(int(sum(primes)), dim)
        gen = torch.Generator().manual_seed(seed)
        with torch.no_grad():
            self.emb.weight.copy_(torch.randn(self.emb.weight.shape, generator=gen) * 0.02)
        self.emb.weight.requires_grad_(not frozen)
        self.proj = nn.Linear(len(self.orders) * heads * dim, hidden)
        nn.init.zeros_(self.proj.weight)
        nn.init.zeros_(self.proj.bias)

    def forward(self, ids):  # ids [B, T] -> [B, T, hidden], n-grams ending at each position
        B, T = ids.shape
        idx = []
        for oi, n in enumerate(self.orders):
            mix = torch.zeros_like(ids)
            for k in range(n):
                shifted = F.pad(ids, (k, 0), value=0)[:, :T]
                mix = mix ^ (shifted * self.mult[oi, k])
            for h in range(self.heads):
                j = oi * self.heads + h
                idx.append(torch.remainder(mix, self.primes[j]) + self.offsets[j])
        e = self.emb(torch.stack(idx, dim=-1))  # [B, T, H, dim]
        return self.proj(e.flatten(-2))


class DraftHeads(nn.Module):
    def __init__(self, hidden, k=4, mult=1, table=None, embed=None):
        super().__init__()
        self.k = k
        self.tok_proj = nn.Linear(hidden, hidden)  # embedding of x[t+1], zero-init
        nn.init.zeros_(self.tok_proj.weight)
        nn.init.zeros_(self.tok_proj.bias)
        self.embed = embed  # frozen input embedding of the base
        self.table = table
        inner = hidden * mult
        self.up = nn.ModuleList([nn.Linear(hidden, inner) for _ in range(k)])
        self.down = nn.ModuleList([nn.Linear(inner, hidden) for _ in range(k)])
        for d in self.down:
            nn.init.zeros_(d.weight)
            nn.init.zeros_(d.bias)

    def forward(self, h, ids):
        """h [B, T, H]: base final hidden at t. ids [B, T]: tokens. Returns per-head hidden
        for positions t = 0..T-2 (needs x[t+1] = ids[:, t+1])."""
        nxt = ids[:, 1:]
        x = h[:, :-1] + self.tok_proj(self.embed(nxt).to(h.dtype))
        if self.table is not None:
            x = x + self.table(ids)[:, 1:]  # n-grams ending at t+1
        return [x + d(F.silu(u(x))) for u, d in zip(self.up, self.down)]


# ----------------------------------------------------------------------------- core

@torch.no_grad()
def base_hidden(model, ids):
    return model.model(input_ids=ids).last_hidden_state


def head_loss(heads, lm_head, h, ids):
    outs = heads(h, ids)  # each [B, T-1, H] for t = 0..T-2
    loss = 0.0
    for j, o in enumerate(outs, start=1):  # head j predicts x[t+1+j]
        L = ids.shape[1] - 1 - j
        logits = lm_head(o[:, :L])
        loss = loss + F.cross_entropy(logits.float().reshape(-1, logits.shape[-1]), ids[:, 1 + j:].reshape(-1))
    return loss / len(outs)


def train_arms(model, arms, data, args, label):
    lm_head = model.lm_head
    opts = {}
    for name, heads in arms.items():
        groups = [{"params": [p for n, p in heads.named_parameters() if p.requires_grad and "table.emb" not in n],
                   "lr": args.lr, "weight_decay": 0.0}]
        emb = [p for n, p in heads.named_parameters() if p.requires_grad and "table.emb" in n]
        if emb:
            groups.append({"params": emb, "lr": args.table_lr, "weight_decay": 0.0})
        opts[name] = torch.optim.AdamW(groups, betas=(0.9, 0.95))
        heads.train()
    steps = math.ceil(len(data) / args.batch)
    sched = {n: torch.optim.lr_scheduler.OneCycleLR(o, max_lr=[g["lr"] for g in o.param_groups],
                                                     total_steps=steps, pct_start=0.05)
             for n, o in opts.items()}
    perm = torch.randperm(len(data), generator=torch.Generator().manual_seed(0))
    log = {n: [] for n in arms}
    t0 = time.time()
    for s in range(steps):
        ids = data[perm[s * args.batch:(s + 1) * args.batch]].to(args.device)
        with torch.autocast(args.device_type, dtype=torch.bfloat16, enabled=args.device_type == "cuda"):
            h = base_hidden(model, ids)
            for name, heads in arms.items():
                loss = head_loss(heads, lm_head, h, ids)
                opts[name].zero_grad(set_to_none=True)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(heads.parameters(), 1.0)
                opts[name].step()
                sched[name].step()
                if s % 50 == 0 or s == steps - 1:
                    log[name].append((s, float(loss)))
        if s % 200 == 0 or s == steps - 1:
            msg = " ".join(f"{n}={log[n][-1][1]:.3f}" for n in arms)
            print(f"[{label}] step {s + 1}/{steps} {msg} ({time.time() - t0:.0f}s)", flush=True)
    for heads in arms.values():
        heads.eval()
    return log


@torch.no_grad()
def generate(model, prompts, n_new, batch, device):
    outs = []
    for i in range(0, len(prompts), batch):
        p = prompts[i:i + batch].to(device)
        g = model.generate(p, attention_mask=torch.ones_like(p), max_new_tokens=n_new, min_new_tokens=n_new,
                           do_sample=False, pad_token_id=model.config.eos_token_id or 0)
        outs.append(g.cpu())
    return torch.cat(outs)


def build_lookup(train_ids, V):
    """Most frequent next token after each (a, b) bigram in the training tokens."""
    x = train_ids.reshape(-1).numpy().astype(np.int64)
    key = x[:-2] * V + x[1:-1]
    nxt = x[2:]
    order = np.lexsort((nxt, key))
    k, n = key[order], nxt[order]
    pair = k * V + n
    starts = np.r_[0, np.flatnonzero(np.diff(pair)) + 1]
    counts = np.diff(np.r_[starts, len(pair)])
    uk, un = k[starts], n[starts]
    # per key, keep the next token with the highest count
    best = {}
    for kk, nn_, cc in zip(uk.tolist(), un.tolist(), counts.tolist()):
        if cc > best.get(kk, (None, 0))[1]:
            best[kk] = (nn_, cc)
    return {kk: v[0] for kk, v in best.items()}, V


@torch.no_grad()
def acceptance(model, seqs, plen, arms, lookup, K, device, batch):
    """Mean tokens per verification step (1 + accepted draft tokens) for each drafter."""
    res = {n: [] for n in list(arms) + ["lookup", "domain+lookup"]}
    first = {n: [] for n in res}
    table, V = lookup
    for i in range(0, len(seqs), batch):
        ids = seqs[i:i + batch].to(device)
        with torch.autocast("cuda", dtype=torch.bfloat16, enabled=device.startswith("cuda")):
            h = base_hidden(model, ids)
            drafts = {}
            for name, heads in arms.items():
                outs = heads(h, ids)
                drafts[name] = torch.stack([model.lm_head(o).argmax(-1) for o in outs], -1)  # [B, T-1, K]
        T = ids.shape[1]
        pos = range(plen - 1, T - 1 - K)  # draft positions inside the generated continuation
        tgt = torch.stack([ids[:, 1 + j: T - K + j] for j in range(1, K + 1)], -1)  # x[t+1+j], t=0..T-2-K
        for name, d in drafts.items():
            ok = (d[:, :T - 1 - K] == tgt)[:, plen - 1:]
            m = ok.int().cumprod(-1).sum(-1)
            res[name].append(m.cpu())
            first[name].append(ok[..., 0].cpu())
        # training-free lookup chain from (x[t], x[t+1])
        idsn = ids.cpu().numpy()
        lm = np.zeros((ids.shape[0], len(pos)), dtype=np.int64)
        for b in range(ids.shape[0]):
            for pi, t in enumerate(pos):
                a, c = int(idsn[b, t]), int(idsn[b, t + 1])
                m = 0
                for j in range(1, K + 1):
                    nx = table.get(a * V + c)
                    if nx is None or nx != idsn[b, t + 1 + j]:
                        break
                    m += 1
                    a, c = c, nx
                lm[b, pi] = m
        lm_t = torch.from_numpy(lm)
        res["lookup"].append(lm_t)
        first["lookup"].append(lm_t > 0)
        hyb = torch.maximum(res["domain"][-1], lm_t)
        res["domain+lookup"].append(hyb)
        first["domain+lookup"].append(hyb > 0)
    return {n: {"tokens_per_step": 1 + float(torch.cat(v).float().mean()),
                "first_draft_accept": float(torch.cat(first[n]).float().mean())} for n, v in res.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="Qwen/Qwen3-0.6B-Base")
    ap.add_argument("--biomed", required=True, help="Biomed-Enriched parquet")
    ap.add_argument("--train_tokens", type=float, default=10e6)
    ap.add_argument("--seq_len", type=int, default=512)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--k", type=int, default=4)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--table_lr", type=float, default=5e-3)
    ap.add_argument("--table_rows", type=int, default=20000)
    ap.add_argument("--eval_prompts", type=int, default=300)
    ap.add_argument("--prompt_len", type=int, default=64)
    ap.add_argument("--gen_tokens", type=int, default=128)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    args.device_type = "cuda" if args.device.startswith("cuda") else "cpu"
    torch.manual_seed(0)

    from transformers import AutoModelForCausalLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(args.model)
    dtype = torch.bfloat16 if args.device_type == "cuda" else torch.float32
    model = AutoModelForCausalLM.from_pretrained(args.model, dtype=dtype).to(args.device).eval()
    for p in model.parameters():
        p.requires_grad_(False)
    H, V = model.config.hidden_size, model.config.vocab_size
    embed = model.get_input_embeddings()

    def mk(mult=1, table=None):
        return DraftHeads(H, args.k, mult, table, embed).to(args.device)

    bio_train = lambda la, do, ed: la == "en" and do == "biomedical" and (ed or 0) > 4.0
    bio_eval = lambda la, do, ed: la == "en" and do == "biomedical" and (ed or 0) < 4.0
    n_docs = int(args.train_tokens / 150) + 1000
    print("loading data", flush=True)
    bio = pack_tokens(iter_parquet_texts(args.biomed, bio_train, n_docs), tok, args.train_tokens, args.seq_len)
    gen = pack_tokens(iter_hf_texts("HuggingFaceFW/fineweb-edu", "sample-10BT", n_docs), tok,
                      args.train_tokens, args.seq_len)
    bio_p = prompts_from(iter_parquet_texts(args.biomed, bio_eval, 20 * args.eval_prompts), tok,
                         args.eval_prompts, args.prompt_len)
    gen_p = prompts_from(iter_hf_texts("HuggingFaceFW/fineweb-edu", "sample-10BT", 20 * args.eval_prompts,
                                       skip=n_docs + 1000), tok, args.eval_prompts, args.prompt_len)
    print(f"train tokens: biomed {bio.numel():,} general {gen.numel():,}; prompts {len(bio_p)}/{len(gen_p)}",
          flush=True)

    domain_arms = {
        "domain": mk(),
        "domain_big": mk(mult=4),
        "domain_table": mk(table=NgramTable(H, rows=args.table_rows)),
        "domain_rand": mk(table=NgramTable(H, rows=args.table_rows, frozen=True)),
    }
    generic_arms = {"generic": mk()}
    params = {n: {"trainable": sum(p.numel() for p in a.parameters() if p.requires_grad),
                  "total_excl_embed": sum(p.numel() for n2, p in a.named_parameters() if not n2.startswith("embed"))}
              for n, a in {**generic_arms, **domain_arms}.items()}
    print("params", json.dumps(params), flush=True)

    t0 = time.time()
    logs = train_arms(model, generic_arms, gen, args, "general")
    logs.update(train_arms(model, domain_arms, bio, args, "biomed"))
    train_s = time.time() - t0

    print("building lookup + generating eval continuations", flush=True)
    lookup = build_lookup(bio, V)
    gb = 32 if args.device_type == "cuda" else 2
    seqs = {"biomed": generate(model, bio_p, args.gen_tokens, gb, args.device),
            "general": generate(model, gen_p, args.gen_tokens, gb, args.device)}
    arms = {**generic_arms, **domain_arms}
    results = {d: acceptance(model, s, args.prompt_len, arms, lookup, args.k, args.device, gb)
               for d, s in seqs.items()}
    out = {"args": {k: v for k, v in vars(args).items()}, "params": params, "train_seconds": train_s,
           "lookup_keys": len(lookup[0]), "results": results,
           "final_train_loss": {n: l[-1][1] for n, l in logs.items()}, "loss_log": logs}
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        json.dump(out, f, indent=1)
    print("\n| drafter | biomed tokens/step | biomed 1st-draft accept | general tokens/step | general 1st-draft accept |")
    print("|---|---|---|---|---|")
    for n in results["biomed"]:
        b, g = results["biomed"][n], results["general"][n]
        print(f"| {n} | {b['tokens_per_step']:.3f} | {b['first_draft_accept']:.3f} | "
              f"{g['tokens_per_step']:.3f} | {g['first_draft_accept']:.3f} |")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
    os._exit(0)  # streaming datasets threads can crash interpreter shutdown
